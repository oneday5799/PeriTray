#!/bin/sh
# 第零批验收脚本（P3-14：RAII 守卫命名约定）
#
# 用法：在仓库根执行 `sh tools/verify-batch-0.sh`
# 依据：主方案 §6.3「每批的验收清单写法」的实操建议——「把每批的验收段写成
#       tools/verify-batch-N.sh，随该批提交一起入库，这样将来任何人回看都能直接重跑」。
#
# ⚠️ 两条硬约定（主方案 §6.3 末尾，写脚本时踩过的坑）：
#   1) `grep -c` 在**零匹配**时退出码为 **1** ⇒ 一律「赋值给变量再比较」，
#      **不要**用 `set -e`、也不要用 `&&` 串（会假绿或中断）。
#   2) 「回归项」≠「验收项」：回归项防的是**今后新增误用**，它在修复前后取值相同，
#      **不能**作为「这批修好了」的证据。本脚本把两类分开标注。
#
# ⚠️ 本批是**纯文档修复**（P3-14 只改 AGENTS.md 的命名约定，不动代码）⇒
#    验收项只能是**评审**（主方案 §6.3 末尾的边界声明：凡改动本身是文档/规范的条目，
#    「不要给它们编造一个『命令』」）。脚本给出定位命令 + 需人工确认的原文。

cd "$(dirname "$0")/.." || exit 2

fail=0
chk_eq() { # chk_eq <名称> <实得> <期望>
  if [ "$2" = "$3" ]; then
    printf 'PASS  %s（实得 %s）\n' "$1" "$2"
  else
    printf 'FAIL  %s（期望 %s，实得 %s）\n' "$1" "$3" "$2"
    fail=1
  fi
}
chk_ge() { # chk_ge <名称> <实得> <下限>
  if [ "$2" -ge "$3" ] 2>/dev/null; then
    printf 'PASS  %s（实得 %s ≥ %s）\n' "$1" "$2" "$3"
  else
    printf 'FAIL  %s（期望 ≥ %s，实得 %s）\n' "$1" "$3" "$2"
    fail=1
  fi
}

echo "== 第零批（P3-14）验收 =="

# ── 回归项（不是验收项）────────────────────────────────────────────
# 主方案 §6.3 原写「应为 7」，那是**当时的**基线（bluetooth.rs 6 处 + tray.rs:285）。
# 2026-09-18 实测为 **25 处 / 7 个文件**——后续批次（P3-13 把 SingleFlightGuard 上移
# state.rs、P2-11 风格统一等）新增了合法的内层 Drop-only 守卫，基线自然增长。
#
# ⚠️ **本条是「计数式」检查，没有判别力**：它数的是文本出现次数，分不出
# 「外层守卫误加下划线」（真问题）与「内层 `let _guard = guard;`」（正确写法）。
# 若把它当硬闸门，**任何新增的合法守卫都会让它转红**，结果是训练人忽略本脚本。
# 故这里只打印计数与构成供人工比对，**不失败**。
n=$(grep -rn --include="*.rs" "let _[a-zA-Z_][a-zA-Z0-9_]* = " src-tauri/src/ | wc -l | tr -d ' ')
printf 'INFO  回归项：`let _<name> = ` 计数 = %s（2026-09-18 基线 25；主方案 §6.3 写的 7 已过时）\n' "$n"
printf '      按文件构成：\n'
grep -rn --include="*.rs" "let _[a-zA-Z_][a-zA-Z0-9_]* = " src-tauri/src/ \
  | sed 's/:.*//' | sort | uniq -c | sed 's/^/        /'
printf '      ⇒ 若计数变化，人工确认新增的是「内层 Drop-only 守卫」还是「外层误加下划线」。\n'

# ── 验收项（评审类）─────────────────────────────────────────────────
# 主方案 §6.3 原命令：`grep -n "需要被闭包捕获的守卫" AGENTS.md`（修复前 0 命中）。
# ⚠️ **该命令现已失效**：AGENTS.md 落地时的措辞是
#   「**需要被 `move` 闭包捕获的守卫（外层绑定）不得以 `_` 开头**」——
#   中间插了行内代码 `` `move` ``，所以按原字面串搜**恒为 0**。
# ⇒ 判据必须落在**稳定词元**上（「闭包捕获的守卫」），而不是会随行文变动的整句。
n=$(grep -c "闭包捕获的守卫" AGENTS.md || true)
chk_ge "验收项：AGENTS.md 已含「闭包捕获的守卫」命名约定（评审类定位命令）" "$n" 1

echo "  ---- 需人工评审的原文（AGENTS.md「代码与注释风格」节）----"
grep -n "RAII 守卫的绑定命名" -A 6 AGENTS.md | sed 's/^/  /'
echo "  ⇒ 人工确认三件事：① 约定说的是「外层守卫」而非「所有守卫」；"
echo "     ② 明确写了内层 Drop-only 守卫（如 let _guard = guard;）是正确写法；"
echo "     ③ 指向了报告 P3-14。"

echo
if [ "$fail" = "0" ]; then
  echo "第零批验收：通过（回归项为 INFO，需人工比对）"
else
  echo "第零批验收：**未通过**"
  exit 1
fi
